#!/bin/bash

# Exit on error
set -e

echo "Starting build process..."

# Bundle Workbox locally. The shell manifest is injected after the application
# build so unchanged shell assets retain their existing Workbox cache entries.
ONLYOFFICE_SW_OUT_DIR=.onlyoffice-sw ./node_modules/.bin/vite build -c vite.sw.config.ts

# Run Vite build through the project-local binary.
./node_modules/.bin/vite build

node scripts/verify-office-host-identity.mjs

node scripts/inject-service-worker.mjs

# Finish every content mutation before hashing the deployable runtime.
node scripts/patch-onlyoffice-print-fallback.mjs dist

# Derive the Service Worker identity from its exact generated bytes so rebuilds
# of the same source are reproducible and every shell change advances revision.
node scripts/inject-build-revision.mjs dist/sw.js

# Keep the deployable demo/runtime lean by removing low-frequency bundled
# assets and emitting canonical path packs for per-document-type CDN sync.
# This must run after content patching so manifest revisions match final bytes.
node scripts/build-onlyoffice-runtime-assets.mjs \
    --input dist \
    --prune-root \
    --split-output .onlyoffice-runtime-asset-packs

# Stage additive content-addressed objects and the immutable Release Manifest.
# Deployment uploads these objects first and switches channels/stable.json last.
node scripts/build-release-manifest.mjs \
    --root dist \
    --output .onlyoffice-release \
    --package-version "$(node -p "require('./package.json').version")"

echo "Build completed successfully!"
